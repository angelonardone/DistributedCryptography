namespace GeneXus.Programs.wallet {
   public class downloadfile : GXProcedure
   {
      public downloadfile( )
      {
         context = new GxContext(  );
         DataStoreUtil.LoadDataStores( context);
         dsDefault = context.GetDataStore("Default");
         IsMain = true;
      }

      public downloadfile( IGxContext context )
      {
         this.context = context;
         IsMain = false;
         dsDefault = context.GetDataStore("Default");
      }

      public void execute( string aP0_token )
      {
         this.AV2token = aP0_token;
         initialize();
         ExecuteImpl();
      }

      public void executeSubmit( string aP0_token )
      {
         this.AV2token = aP0_token;
         SubmitImpl();
      }

      protected override void ExecutePrivate( )
      {
         /* GeneXus formulas */
         /* Output device settings */
         args = new Object[] {(string)AV2token} ;
         ClassLoader.Execute("wallet.adownloadfile","GeneXus.Programs","wallet.adownloadfile", new Object[] {context }, "execute", args);
         if ( ( args != null ) && ( args.Length == 1 ) )
         {
         }
         cleanup();
      }

      public override void cleanup( )
      {
         CloseCursors();
         if ( IsMain )
         {
            context.CloseConnections();
         }
      }

      public override void initialize( )
      {
         /* GeneXus formulas. */
      }

      private string AV2token ;
      private IGxDataStore dsDefault ;
      private Object[] args ;
   }

